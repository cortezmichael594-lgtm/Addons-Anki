def norm_lang(code: str) -> str:
    code = code.replace("-", "_")
    if code[:2].lower() == "zh":
        return "zh_TW" if any(tag in code.upper() for tag in ("TW", "HK", "MO")) else "zh_CN"
    return code.split("_")[0].lower()


def raw_lang_code() -> str:
    """Codigo de idioma tal cual lo tiene Anki, p. ej. "es_ES" o "pt_BR"."""
    try:
        import anki.lang

        raw_code = (
            getattr(anki.lang, "current_lang", None)
            or getattr(anki.lang, "currentLang", None)
            or ""
        )
        return raw_code if isinstance(raw_code, str) else ""
    except Exception:
        return ""


# El idioma de Anki solo cambia reiniciando, pero se guarda en cache y se
# invalida con reset() al abrir un perfil: asi t() no repite el trabajo de
# resolucion en cada una de las ~400 llamadas que hace un dibujado completo.
_lang_cache: str | None = None


def lang() -> str:
    global _lang_cache
    if _lang_cache is None:
        key = norm_lang(raw_lang_code())
        _lang_cache = key if key in STRINGS else "en"
    return _lang_cache


def reset() -> None:
    """Olvida el idioma cacheado (se llama al abrir o cambiar de perfil)."""
    global _lang_cache
    _lang_cache = None


def t(key: str) -> str:
    return STRINGS[lang()].get(key, STRINGS["en"].get(key, key))


def fill(key: str, **values: object) -> str:
    """Sustituye los huecos {nombre} de un texto propio del complemento."""
    text = t(key)
    for name, value in values.items():
        text = text.replace("{" + name + "}", str(value))
    return text


